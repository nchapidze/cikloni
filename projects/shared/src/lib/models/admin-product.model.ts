import { LocalizedText } from '../i18n/localized-text';
import { AbsorbencyLevel, Size } from './product.model';

/** A variant with this many items or fewer gets the low-stock warning. */
export const LOW_STOCK_THRESHOLD = 3;

export const ABSORBENCY_LEVELS: readonly AbsorbencyLevel[] = ['light', 'medium', 'heavy'];

export interface AdminProductListItem {
  id: string;
  slug: string;
  name: LocalizedText;
  priceGel: number | null;
  absorbency: AbsorbencyLevel;
  isActive: boolean;
  /** Sum over all variants. */
  totalStock: number;
  variantCount: number;
  /** Some variant has LOW_STOCK_THRESHOLD items or fewer. */
  lowStock: boolean;
  /** The first image by sort order, if any. */
  imageUrl: string | null;
}

/** A product as the edit form loads and saves it (all variants and images, active or not). */
export interface AdminProduct {
  /** Generated by the client for a new product, so images can be uploaded under it. */
  id: string;
  slug: string;
  name: LocalizedText;
  description: LocalizedText | null;
  care: LocalizedText | null;
  priceGel: number | null;
  absorbency: AbsorbencyLevel;
  sortOrder: number;
  isActive: boolean;
  variants: AdminVariant[];
  images: AdminImage[];
}

export interface AdminVariant {
  /** null for a variant that is not saved yet. */
  id: string | null;
  colorId: string;
  colorName: LocalizedText;
  /** "#rrggbb" */
  colorHex: string;
  size: Size;
  stock: number;
  /** Stock when the form loaded it; the server applies (stock - loadedStock) to the current value. */
  loadedStock: number | null;
  sku: string;
}

export interface AdminImage {
  /** null for an image that is not saved yet. */
  id: string | null;
  /** Path inside the product-images bucket. */
  storagePath: string;
  /** null = shown for every color. */
  colorId: string | null;
}

/** Why a product was not saved (save_product errors, plus upload and network failures). */
export type ProductSaveFailure =
  | 'FORBIDDEN'
  | 'SLUG_TAKEN'
  | 'SKU_TAKEN'
  | 'DUPLICATE_VARIANT'
  | 'STOCK_CHANGED'
  | 'INVALID_PRODUCT'
  | 'UPLOAD_FAILED'
  | 'NETWORK';

/**
 * URL slug from (English) text: lowercase a-z and 0-9 words joined by hyphens, matching the
 * products.slug check. Other characters (including Georgian) are dropped.
 */
export function slugify(text: string): string {
  return text
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export const SLUG_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;
export const HEX_COLOR_PATTERN = /^#[0-9a-fA-F]{6}$/;
